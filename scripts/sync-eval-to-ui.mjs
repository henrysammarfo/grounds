/**
 * Sync cases/ + out/ into src/lib/eval-live.generated.ts for the dashboard.
 * Run after: python baseline/run.py --all && python agent/run.py --all && python eval/score.py
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const casesDir = path.join(root, "cases");
const outDir = path.join(root, "out");
const index = JSON.parse(fs.readFileSync(path.join(casesDir, "INDEX.json"), "utf8"));

function readJson(p, fallback = null) {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch {
    return fallback;
  }
}

function slugify(s) {
  return String(s)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function statusFor(gold, baseline, grounds) {
  const ids = Object.keys(gold);
  if (!ids.length) return "queued";
  if (!Object.keys(grounds).length) return "queued";
  let mismatch = false;
  let needsHuman = false;
  for (const id of ids) {
    if (grounds[id] !== gold[id]) mismatch = true;
    if (grounds[id] === "partial") needsHuman = true;
  }
  if (needsHuman && mismatch) return "needs-human";
  if (mismatch) return "mismatch";
  return "verified";
}

const metrics = readJson(path.join(outDir, "metrics.json"), {
  claim_accuracy: { baseline: null, grounds: null },
  cases_run: 0,
  adversarial_cases: 0,
  per_case: [],
});

const cases = [];
const trajectorySteps = [];
const gateQueue = [];

for (const id of index.cases) {
  const meta = readJson(path.join(casesDir, id, "meta.json"));
  const claims = readJson(path.join(casesDir, id, "claims.json"), []);
  const goldRows = readJson(path.join(casesDir, id, "gold.json"), []);
  const gold = Object.fromEntries(goldRows.map((g) => [g.id, g.label]));
  const base = readJson(path.join(outDir, "baseline", id, "predictions.json"));
  const agent = readJson(path.join(outDir, "agent", id, "report.json"));
  const bmap = Object.fromEntries((base?.predictions || []).map((p) => [p.claim_id, p.label]));
  const amap = Object.fromEntries((agent?.predictions || []).map((p) => [p.claim_id, p.label]));
  const evidenceById = Object.fromEntries(
    (agent?.evidence || []).map((e) => [
      e.claim_id,
      (e.notes || []).slice(0, 3).join(" · ") ||
        (e.sources || []).slice(0, 3).join(", ") ||
        "see report.json",
    ]),
  );

  const claimObjs = claims.map((c) => ({
    id: c.id,
    text: c.text,
    gold: gold[c.id] || "partial",
    baseline: bmap[c.id] || "partial",
    grounds: amap[c.id] || "partial",
    evidence: evidenceById[c.id] || goldRows.find((g) => g.id === c.id)?.rationale || "",
  }));

  cases.push({
    id,
    slug: slugify(meta?.repo || id),
    repo: meta?.repo || id,
    title: meta?.title || id,
    source: meta?.source || "README",
    status: statusFor(gold, bmap, amap),
    hard: Boolean(meta?.hard),
    claims: claimObjs,
    humanMinutes: agent?.timing?.human_minutes ?? 0,
    costUsd: agent?.timing?.cost_usd ?? 0,
    updated: agent ? "Synced from out/" : "Queued",
  });

  for (const g of agent?.gate || []) {
    gateQueue.push({
      id: `G-${id}`,
      case: id,
      action: g.cmd || g.reason || "gated action",
      risk: "medium",
      requested: g.decision || "pending",
    });
  }
}

// Representative trajectory from C-001
const trajPath = path.join(outDir, "agent", "C-001", "trajectory.jsonl");
if (fs.existsSync(trajPath)) {
  const lines = fs.readFileSync(trajPath, "utf8").trim().split(/\r?\n/).slice(1);
  let i = 0;
  for (const line of lines.slice(0, 12)) {
    try {
      const ev = JSON.parse(line);
      trajectorySteps.push({
        id: `T${++i}`,
        node: String(ev.node || "tool").slice(0, 12),
        label: String(ev.kind || ev.node || "step"),
        detail: JSON.stringify(ev.detail || {}).slice(0, 180),
        duration: `${Number(ev.ts || 0).toFixed(2)}s`,
      });
    } catch {
      /* skip */
    }
  }
}

const runs = [
  {
    id: "R-agent",
    pack: "gold-pack-v1",
    mode: "GROUNDS agent",
    cases: metrics.cases_run || cases.length,
    accuracy: metrics.claim_accuracy?.grounds ?? 0,
    duration: "see REPRO",
    cost: null,
    when: "out/agent",
  },
  {
    id: "R-baseline",
    pack: "gold-pack-v1",
    mode: "One-shot baseline",
    cases: metrics.cases_run || cases.length,
    accuracy: metrics.claim_accuracy?.baseline ?? 0,
    duration: "see REPRO",
    cost: null,
    when: "out/baseline",
  },
];

const accuracyByCase = (metrics.per_case || []).map((r) => ({
  name: r.name,
  baseline: r.baseline,
  grounds: r.grounds,
}));

const outTs = `/* AUTO-GENERATED by scripts/sync-eval-to-ui.mjs — do not edit by hand */
export const liveMetrics = ${JSON.stringify(
  {
    claimAccuracy: {
      baseline: metrics.claim_accuracy?.baseline ?? 0,
      grounds: metrics.claim_accuracy?.grounds ?? 0,
    },
    humanMinutes: {
      baseline: metrics.human_minutes_per_case?.baseline ?? 0,
      grounds: metrics.human_minutes_per_case?.grounds ?? 0,
    },
    costPerCase: {
      baseline: metrics.cost_usd_per_case?.baseline ?? 0,
      grounds: metrics.cost_usd_per_case?.grounds ?? 0,
    },
    casesRun: metrics.cases_run || cases.length,
    adversarialCases: metrics.adversarial_cases || cases.filter((c) => c.hard).length,
    source: "out/metrics.json",
  },
  null,
  2,
)} as const;

export const liveAccuracyByCase = ${JSON.stringify(accuracyByCase, null, 2)} as const;

export const liveCases = ${JSON.stringify(cases, null, 2)} as const;

export const liveRuns = ${JSON.stringify(runs, null, 2)} as const;

export const liveTrajectory = ${JSON.stringify(trajectorySteps, null, 2)} as const;

export const liveGateQueue = ${JSON.stringify(gateQueue, null, 2)} as const;
`;

const dest = path.join(root, "src", "lib", "eval-live.generated.ts");
fs.writeFileSync(dest, outTs, "utf8");
console.log("Wrote", dest, "cases=", cases.length, "metrics=", metrics.claim_accuracy);
